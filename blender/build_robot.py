def T(loc=(0, 0, 0), rot=(0, 0, 0), scale=None):
    m = Matrix.Translation(Vector(loc)) @ Euler(rot, "XYZ").to_matrix().to_4x4()
    if scale is not None:
        m = m @ Matrix.Diagonal((*scale, 1.0))
    return m


AX_X = (0, math.pi / 2, 0)      # rotate primitive Z axis onto X
AX_Y = (math.pi / 2, 0, 0)      # rotate primitive Z axis onto Y


class MB:
    """Accumulates primitives into a single bmesh with per-face materials."""

    def __init__(self):
        self.bm = bmesh.new()
        self.mats = []

    # -- internals -------------------------------------------------------- #
    def _mi(self, mat):
        m = MAT[mat]
        if m not in self.mats:
            self.mats.append(m)
        return self.mats.index(m)

    def _finish(self, verts, mat, bevel=0.0, seg=2, angle=0.7):
        idx = self._mi(mat)
        faces = {f for v in verts for f in v.link_faces}
        for f in faces:
            f.material_index = idx
            f.normal_update()
        if bevel > 0:
            edges = {e for f in faces for e in f.edges if e.is_manifold and e.calc_face_angle(0) > angle}
            if edges:
                bmesh.ops.bevel(self.bm, geom=list(edges), offset=bevel, offset_type="OFFSET",
                                segments=seg, profile=0.5, affect="EDGES", clamp_overlap=True,
                                material=idx)
        return self

    def _poly_prism(self, ring_a, ring_b, mat, cap=True):
        """Connect two equal-length vertex rings (lists of Vector) with quads."""
        bm = self.bm
        va = [bm.verts.new(p) for p in ring_a]
        vb = [bm.verts.new(p) for p in ring_b]
        n = len(va)
        for i in range(n):
            j = (i + 1) % n
            bm.faces.new((va[i], va[j], vb[j], vb[i]))
        if cap:
            bm.faces.new(list(reversed(va)))
            bm.faces.new(vb)
        return va + vb

    # -- primitives ------------------------------------------------------- #
    def box(self, size, loc=(0, 0, 0), rot=(0, 0, 0), mat="Anodized_Graphite", bevel=0.004, seg=2):
        r = bmesh.ops.create_cube(self.bm, size=1.0, matrix=T(loc, rot, size))
        return self._finish(r["verts"], mat, bevel, seg)

    def cyl(self, r, h, loc=(0, 0, 0), rot=(0, 0, 0), mat="Anodized_Graphite", seg=32, r2=None,
            bevel=0.0, bseg=2):
        res = bmesh.ops.create_cone(self.bm, cap_ends=True, cap_tris=False, segments=seg, radius1=r,
                                    radius2=r if r2 is None else r2, depth=h, matrix=T(loc, rot))
        return self._finish(res["verts"], mat, bevel, bseg)

    def ring(self, r_in, r_out, h, loc=(0, 0, 0), rot=(0, 0, 0), mat="Anodized_Graphite", seg=32,
             bevel=0.0):
        bm, mtx = self.bm, T(loc, rot)
        rings = []
        for rr, z in ((r_out, -h / 2), (r_out, h / 2), (r_in, h / 2), (r_in, -h / 2)):
            rings.append([bm.verts.new(mtx @ Vector((rr * math.cos(TAU * i / seg),
                                                     rr * math.sin(TAU * i / seg), z))) for i in range(seg)])
        for a, b in zip(rings, rings[1:] + rings[:1]):
            for i in range(seg):
                j = (i + 1) % seg
                bm.faces.new((a[i], a[j], b[j], b[i]))
        return self._finish([v for r_ in rings for v in r_], mat, bevel)

    def torus(self, R, r, loc=(0, 0, 0), rot=(0, 0, 0), mat="Anodized_Graphite", seg=32, seg2=10):
        bm, mtx = self.bm, T(loc, rot)
        grid = []
        for i in range(seg):
            u = TAU * i / seg
            row = []
            for j in range(seg2):
                v = TAU * j / seg2
                p = Vector(((R + r * math.cos(v)) * math.cos(u), (R + r * math.cos(v)) * math.sin(u),
                            r * math.sin(v)))
                row.append(bm.verts.new(mtx @ p))
            grid.append(row)
        for i in range(seg):
            for j in range(seg2):
                a, b = grid[i][j], grid[(i + 1) % seg][j]
                c, d = grid[(i + 1) % seg][(j + 1) % seg2], grid[i][(j + 1) % seg2]
                bm.faces.new((a, b, c, d))
        return self._finish([v for row in grid for v in row], mat)

    def sphere(self, r, loc=(0, 0, 0), mat="Rubber_Black", seg=24, rings=12, scale=(1, 1, 1)):
        res = bmesh.ops.create_uvsphere(self.bm, u_segments=seg, v_segments=rings, radius=r,
                                        matrix=T(loc, (0, 0, 0), scale))
        return self._finish(res["verts"], mat)

    def tapered(self, z0, z1, wx0, wx1, wy, loc=(0, 0, 0), rot=(0, 0, 0), x_off1=0.0,
                mat="Anodized_Graphite", bevel=0.006):
        """Box beam along Z from z0 to z1, width tapering wx0 -> wx1 (X), depth wy."""
        mtx = T(loc, rot)
        a = [mtx @ Vector(p) for p in ((-wx0 / 2, -wy / 2, z0), (wx0 / 2, -wy / 2, z0),
                                       (wx0 / 2, wy / 2, z0), (-wx0 / 2, wy / 2, z0))]
        b = [mtx @ Vector(p) for p in ((x_off1 - wx1 / 2, -wy / 2, z1), (x_off1 + wx1 / 2, -wy / 2, z1),
                                       (x_off1 + wx1 / 2, wy / 2, z1), (x_off1 - wx1 / 2, wy / 2, z1))]
        verts = self._poly_prism(a, b, mat)
        return self._finish(verts, mat, bevel)

    def gear(self, teeth, module, thick, bore, loc=(0, 0, 0), rot=(0, 0, 0), mat="Brass_Gear"):
        rp = module * teeth / 2
        ra, rf = rp + module, rp - 1.25 * module
        prof = []
        for i in range(teeth):
            for frac, rr in ((0.0, rf), (0.20, rf), (0.36, ra), (0.62, ra), (0.78, rf)):
                a = TAU * (i + frac) / teeth
                prof.append((a, rr))
        bm, mtx = self.bm, T(loc, rot)
        n = len(prof)

        def ring_at(rad_fn, z):
            return [bm.verts.new(mtx @ Vector((rad_fn(a, rr) * math.cos(a), rad_fn(a, rr) * math.sin(a), z)))
                    for a, rr in prof]
        ot = ring_at(lambda a, rr: rr, thick / 2)
        ob = ring_at(lambda a, rr: rr, -thick / 2)
        it = ring_at(lambda a, rr: bore, thick / 2)
        ib = ring_at(lambda a, rr: bore, -thick / 2)
        for i in range(n):
            j = (i + 1) % n
            bm.faces.new((ot[i], ot[j], it[j], it[i]))
            bm.faces.new((ob[j], ob[i], ib[i], ib[j]))
            bm.faces.new((ob[i], ob[j], ot[j], ot[i]))
            bm.faces.new((ib[j], ib[i], it[i], it[j]))
        return self._finish(ot + ob + it + ib, mat)

    def tube(self, points, r, mat="Rubber_Black", seg=10, subdiv=6):
        """Swept circular tube through control points (Catmull-Rom smoothed)."""
        P = [Vector(p) for p in points]
        path = []
        for i in range(len(P) - 1):
            p0, p1, p2, p3 = P[max(i - 1, 0)], P[i], P[i + 1], P[min(i + 2, len(P) - 1)]
            for s in range(subdiv):
                t = s / subdiv
                t2, t3 = t * t, t * t * t
                path.append(0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 +
                                   (-p0 + 3 * p1 - 3 * p2 + p3) * t3))
        path.append(P[-1])
        bm = self.bm
        tangent = (path[1] - path[0]).normalized()
        normal = tangent.orthogonal().normalized()
        rings = []
        for i, p in enumerate(path):
            if 0 < i < len(path) - 1:
                nt = (path[i + 1] - path[i - 1]).normalized()
            else:
                nt = (path[min(i + 1, len(path) - 1)] - path[max(i - 1, 0)]).normalized()
            # parallel transport of the normal
            axis = tangent.cross(nt)
            if axis.length > 1e-8:
                ang = math.asin(min(axis.length, 1.0))
                normal = Matrix.Rotation(ang, 3, axis.normalized()) @ normal
            tangent = nt
            binorm = tangent.cross(normal)
            rings.append([bm.verts.new(p + r * (math.cos(TAU * k / seg) * normal + math.sin(TAU * k / seg) * binorm))
                          for k in range(seg)])
        for a, b in zip(rings, rings[1:]):
            for k in range(seg):
                j = (k + 1) % seg
                bm.faces.new((a[k], a[j], b[j], b[k]))
        bm.faces.new(list(reversed(rings[0])))
        bm.faces.new(rings[-1])
        return self._finish([v for rr in rings for v in rr], mat)

    def helix(self, radius, length, turns, wire, loc=(0, 0, 0), rot=(0, 0, 0), mat="Hazard_Yellow"):
        mtx = T(loc, rot)
        n = int(turns * 18)
        pts = [mtx @ Vector((radius * math.cos(TAU * turns * i / n), radius * math.sin(TAU * turns * i / n),
                             length * i / n)) for i in range(n + 1)]
        return self.tube(pts, wire, mat, seg=8, subdiv=1)

    def bolts(self, positions, r=0.0055, h=0.004, rot=(0, 0, 0), mat="Machined_Aluminium"):
        for p in positions:
            self.cyl(r, h, p, rot, mat, seg=6)
        return self

    def bolt_circle(self, n, R, loc, rot, r=0.0045, h=0.004, mat="Machined_Aluminium", z=0.0):
        mtx = T(loc, rot)
        for i in range(n):
            a = TAU * i / n
            p = mtx @ Vector((R * math.cos(a), R * math.sin(a), z))
            res = bmesh.ops.create_cone(self.bm, cap_ends=True, cap_tris=False, segments=6, radius1=r,
                                        radius2=r, depth=h, matrix=Matrix.Translation(p) @ mtx.to_3x3().to_4x4())
            self._finish(res["verts"], mat)
        return self

    def fins(self, r_in, r_out, count, spacing, loc, rot, thick=0.003, mat="Gunmetal"):
        mtx = T(loc, rot)
        for i in range(count):
            z = (i - (count - 1) / 2) * spacing
            p = mtx @ Vector((0, 0, z))
            self.ring(r_in, r_out, thick, tuple(p), rot, mat, seg=32)
        return self

    # -- output ----------------------------------------------------------- #
    def build(self, name, parent=None, loc=(0, 0, 0), rot=(0, 0, 0), coll=None, smooth_angle=34):
        bm = self.bm
        bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-6)
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
        me = bpy.data.meshes.new(name)
        bm.to_mesh(me)
        bm.free()
        for m in self.mats:
            me.materials.append(m)
        for p in me.polygons:
            p.use_smooth = True
        try:
            me.set_sharp_from_angle(angle=math.radians(smooth_angle))
        except Exception:  # Blender < 4.1
            me.use_auto_smooth = True
            me.auto_smooth_angle = math.radians(smooth_angle)
        ob = bpy.data.objects.new(name, me)
        (coll or ROBOT_COLL).objects.link(ob)
        ob.parent = parent
        ob.location = loc
        ob.rotation_euler = rot
        OBJ[name] = ob
        return ob


def empty(name, parent=None, loc=(0, 0, 0), size=0.05, kind="PLAIN_AXES", coll=None):
    ob = bpy.data.objects.new(name, None)
    ob.empty_display_type = kind
    ob.empty_display_size = size
    (coll or ROBOT_COLL).objects.link(ob)
    ob.parent = parent
    ob.location = loc
    OBJ[name] = ob
    return ob


def part(mb, name, parent, category, title, desc, specs=None, explode=(0, 0, 0), loc=(0, 0, 0),
         group="Body", mass=0.0):
    ob = mb.build(name, parent, loc)
    meta = {"title": title, "category": category, "group": group, "description": desc,
            "specs": specs or {}, "mass_kg": mass}
    PARTS[name] = meta
    EXPLODE[name] = explode
    ob["part_title"] = title
    ob["part_category"] = category
    ob["part_group"] = group
    return ob


