def render_stills(out=None, res=(1920, 1080), samples=64, only=None):
    out = out or os.path.join(OUT, "..", "renders")
    os.makedirs(out, exist_ok=True)
    sc = bpy.context.scene
    setup_render(res)
    if hasattr(sc.eevee, "taa_render_samples"):
        sc.eevee.taa_render_samples = samples
    sc.render.image_settings.file_format = "PNG"
    clips = {c["id"]: c for c in M.timeline()}
    shell = [o for n, o in OBJ.items() if PARTS.get(n, {}).get("category") == "shell"]
    # timeline markers switch the active camera on frame change - unbind them while rendering stills
    bound = [(mk, mk.camera) for mk in sc.timeline_markers]
    for mk, _ in bound:
        mk.camera = None
    done = []
    for name, cid, t, cam, hide in SHOTS:
        if only and name not in only:
            continue
        sc.frame_set(clips[cid]["start"] + int(round(t * M.FPS)))
        sc.camera = bpy.data.objects[cam]
        for o in shell:
            o.hide_render = hide
        sc.render.filepath = os.path.join(out, name + ".png")
        bpy.ops.render.render(write_still=True)
        done.append(sc.render.filepath)
    for o in shell:
        o.hide_render = False
    for mk, cam in bound:
        mk.camera = cam
    return done


def render_videos(out=None, ids=None, res=(1280, 720), samples=24):
    """Render each animation clip to its own H.264 MP4 using the bound marker cameras."""
    out = out or os.path.join(OUT, "..", "videos")
    os.makedirs(out, exist_ok=True)
    sc = bpy.context.scene
    setup_render(res)
    if hasattr(sc.eevee, "taa_render_samples"):
        sc.eevee.taa_render_samples = samples
    r = sc.render
    if hasattr(r.image_settings, "media_type"):      # Blender 5.0+
        r.image_settings.media_type = "VIDEO"
    r.image_settings.file_format = "FFMPEG"
    r.ffmpeg.format = "MPEG4"
    r.ffmpeg.codec = "H264"
    r.ffmpeg.constant_rate_factor = "HIGH"
    r.ffmpeg.ffmpeg_preset = "GOOD"
    r.use_file_extension = True
    done = []
    fs, fe = sc.frame_start, sc.frame_end
    for i, c in enumerate(M.timeline()):
        if ids and c["id"] not in ids:
            continue
        sc.frame_start, sc.frame_end = c["start"], c["end"]
        r.filepath = os.path.join(out, f"{i + 1:02d}_{c['id']}_")
        bpy.ops.render.render(animation=True)
        done.append(c["id"])
    sc.frame_start, sc.frame_end = fs, fe
    if hasattr(r.image_settings, "media_type"):
        r.image_settings.media_type = "IMAGE"
    r.image_settings.file_format = "PNG"
    return done


