def export_all(out=OUT, save_blend=True):
    os.makedirs(out, exist_ok=True)
    sc = bpy.context.scene
    # pick a powered, standing frame so exported emissive values are non-zero
    idle = [c for c in M.timeline() if c["id"] == "idle"][0]
    sc.frame_set(idle["start"])
    for ob in bpy.context.view_layer.objects:
        ob.select_set(False)
    for coll in (ROBOT_COLL, PROPS_COLL):
        for ob in coll.all_objects:
            ob.select_set(True)
    props = bpy.ops.export_scene.gltf.get_rna_type().properties.keys()
    want = dict(filepath=os.path.join(out, "argo_q4.glb"), export_format="GLB", use_selection=True,
                export_extras=True, export_animations=True, export_force_sampling=True,
                export_animation_mode="SCENE", export_optimize_animation_size=True,
                export_anim_single_armature=False, export_cameras=False, export_lights=False,
                export_yup=True, export_apply=False, export_frame_range=True,
                export_bake_animation=True, export_def_bones=False, export_materials="EXPORT",
                export_image_format="NONE", export_texcoords=False, export_normals=True,
                export_attributes=False, export_skins=False, export_morph=False)
    kwargs = {k: v for k, v in want.items() if k in props}
    if "export_animation_mode" in kwargs:
        modes = [i.identifier for i in bpy.ops.export_scene.gltf.get_rna_type().properties["export_animation_mode"].enum_items]
        if "SCENE" not in modes:
            kwargs["export_animation_mode"] = "ACTIVE_ACTIONS"
    bpy.ops.export_scene.gltf(**kwargs)

    tl = M.timeline()
    with open(os.path.join(out, "clips.json"), "w", encoding="utf-8") as fh:
        json.dump({"fps": M.FPS, "frame_start": 1, "frame_end": tl[-1]["end"],
                   "clips": [{k: c[k] for k in ("id", "label", "desc", "start", "end", "frames", "loop", "dur")}
                             for c in tl]}, fh, indent=2)
    with open(os.path.join(out, "parts.json"), "w", encoding="utf-8") as fh:
        json.dump(PARTS, fh, indent=2, ensure_ascii=False)
    if save_blend:
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(out, "argo_q4.blend"), compress=True)
    return kwargs


