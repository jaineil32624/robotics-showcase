def _fcurves_for(ob):
    ad = ob.animation_data or ob.animation_data_create()
    act = bpy.data.actions.new(ob.name + "_Action")
    ad.action = act
    if hasattr(act, "slots"):            # Blender 4.4+ layered actions
        slot = act.slots.new(id_type="OBJECT", name=ob.name)
        ad.action_slot = slot
        from bpy_extras import anim_utils
        return anim_utils.action_ensure_channelbag_for_slot(act, slot).fcurves
    return act.fcurves


class Recorder:
    def __init__(self):
        self.data = {}      # (obj_name, path, index) -> list of (frame, value)

    def rec(self, ob, path, values, frame):
        for i, v in enumerate(values):
            self.data.setdefault((ob.name, path, i), []).append((frame, float(v)))

    def write(self):
        by_obj = {}
        for (name, path, idx), samples in self.data.items():
            vals = [v for _, v in samples]
            if max(vals) - min(vals) < 1e-7:
                continue
            by_obj.setdefault(name, []).append((path, idx, samples))
        n = 0
        for name, chans in by_obj.items():
            ob = bpy.data.objects[name]
            fcs = _fcurves_for(ob)
            for path, idx, samples in chans:
                fc = fcs.new(path, index=idx)
                fc.keyframe_points.add(len(samples))
                flat = [c for s in samples for c in s]
                fc.keyframe_points.foreach_set("co", flat)
                try:
                    fc.keyframe_points.foreach_set("interpolation", [1] * len(samples))   # LINEAR
                except Exception:
                    for kp in fc.keyframe_points:
                        kp.interpolation = "LINEAR"
                fc.update()
                n += 1
        return n


def _aim_quat(parent, origin_world, target_world):
    """Quaternion (in parent space) pointing local +Z from origin towards target."""
    pinv = parent.matrix_world.to_3x3().inverted()
    d = pinv @ (target_world - origin_world)
    return d.to_track_quat("Z", "Y"), d.length


def bake_animation(rig):
    sc = bpy.context.scene
    tl = M.timeline()
    sc.frame_start, sc.frame_end = 1, tl[-1]["end"]
    rec = Recorder()
    vl = bpy.context.view_layer
    body, root, power = rig["body"], rig["root"], rig["power"]
    # base locations for explode offsets
    base_loc = {n: OBJ[n].location.copy() for n in EXPLODE}
    knee_d = {leg: [] for leg in M.LEGS}
    crate = OBJ["Sample_Crate"]
    stand = OBJ["Work_Stand"]
    crate_home = Matrix.Translation((M.STAND_POS[0], M.STAND_POS[1], M.STAND_H + M.CRATE_SIZE / 2))
    t0 = time.time()
    for clip in tl:
        ang = {"lidar": 0.0, "fan": 0.0, "pump": 0.0}
        grasp_off = None
        deck_off = None
        drop = None
        for i in range(clip["frames"]):
            f = clip["start"] + i
            p = M.sample(clip, i)
            dt = 1.0 / M.FPS
            for k in ang:
                ang[k] += TAU * p["omega"][k] * dt
            # ---------------- joints ----------------
            rx, ry, ryaw = p["root"]
            root.location = (rx, ry, 0.0)
            root.rotation_euler = (0, 0, ryaw)
            bx, by, bz, roll, pitch = p["body"]
            body.location = (bx, by, bz)
            body.rotation_euler = (roll, pitch, 0.0)
            for leg, (a, h, k) in p["legs"].items():
                rig["abd"][leg].rotation_euler = (a, 0, 0)
                rig["hip"][leg].rotation_euler = (0, h, 0)
                rig["knee"][leg].rotation_euler = (0, k, 0)
            arm = p["arm"]
            rig["turret"].rotation_euler = (0, 0, arm["turret"])
            rig["shoulder"].rotation_euler = (0, arm["shoulder"], 0)
            rig["elbow"].rotation_euler = (0, arm["elbow"], 0)
            rig["wpitch"].rotation_euler = (0, arm["wpitch"], 0)
            rig["wroll"].rotation_euler = (arm["wroll"], 0, 0)
            fo = M.finger_offset(p["grip"])
            rig["fingers"][0].location = (0.04, fo, 0)
            rig["fingers"][1].location = (0.04, -fo, 0)
            OBJ["Lidar_Rotor"].rotation_euler = (0, 0, ang["lidar"])
            OBJ["Cooling_Fan_Rotor"].rotation_euler = (ang["fan"], 0, 0)
            g = ang["pump"]
            OBJ["Gear_Drive"].rotation_euler = (0, 0, g)
            OBJ["Gear_Idler"].rotation_euler = (0, 0, math.pi / 14 - g * 20 / 14)
            OBJ["Gear_Output"].rotation_euler = (0, 0, g * 20 / 28)
            power.scale = (max(p["power"], 1e-4), 1, 1)
            vl.update()

            # ---------------- hydraulics (aimed) ----------------
            for leg in M.LEGS:
                cyl, rod = OBJ.get(f"Knee_Cylinder_{leg}"), OBJ.get(f"Knee_Rod_{leg}")
                jh, jk = rig["hip"][leg], rig["knee"][leg]
                off = M.LEGS[leg][1] * KNEE_OFF_Y
                a_w = jh.matrix_world @ Vector((KNEE_A[0], off, KNEE_A[1]))
                b_w = jk.matrix_world @ Vector((KNEE_B[0], off, KNEE_B[1]))
                if cyl is None:
                    knee_d[leg].append((a_w - b_w).length)
                    continue
                q, _ = _aim_quat(jh, a_w, b_w)
                cyl.rotation_quaternion = q
                q2, _ = _aim_quat(jk, b_w, a_w)
                rod.rotation_quaternion = q2
                rec.rec(cyl, "rotation_quaternion", q, f)
                rec.rec(rod, "rotation_quaternion", q2, f)

            # ---------------- props & crate physics ----------------
            if p["props"]:
                stand.scale = (1, 1, 1)
                ev = p["events"]
                wr = rig["wroll"].matrix_world @ Matrix.Translation((M.L_GRIP - 0.06, 0, 0))
                if ev.get("grasp"):
                    if grasp_off is None:
                        grasp_off = wr.inverted() @ crate_home
                    mw = wr @ grasp_off
                elif ev.get("release"):
                    if deck_off is None:
                        release_mw = wr @ grasp_off if grasp_off else crate_home
                        deck_off = body.matrix_world.inverted() @ release_mw
                        drop = {"z": 0.0, "v": 0.0}
                    # drop the last few millimetres onto the deck (ballistic + restitution)
                    deck_top = M.DECK_POS[2] + M.CRATE_SIZE / 2
                    gap = deck_off.translation.z - deck_top
                    for _ in range(8):
                        drop["v"] -= 9.81 * dt / 8
                        drop["z"] += drop["v"] * dt / 8
                        if gap + drop["z"] < 0:
                            drop["z"] = -gap
                            drop["v"] = -drop["v"] * 0.3
                    off = deck_off.copy()
                    off.translation.z += drop["z"]
                    mw = body.matrix_world @ off
                else:
                    mw = crate_home
                crate.matrix_world = mw
                crate.scale = (1, 1, 1)
            else:
                stand.scale = (0, 0, 0)
                crate.matrix_world = crate_home
                crate.scale = (0, 0, 0)
            # decompose the target matrix (matrix_world reads are stale until the next depsgraph update)
            loc, rot, _ = (mw if p["props"] else crate_home).decompose()
            rec.rec(crate, "location", loc, f)
            rec.rec(crate, "rotation_quaternion", rot, f)
            rec.rec(crate, "scale", (1, 1, 1) if p["props"] else (0, 0, 0), f)
            rec.rec(stand, "scale", (1, 1, 1) if p["props"] else (0, 0, 0), f)

            # ---------------- explode ----------------
            e = p["explode"]
            bw = body.matrix_world.to_3x3()
            for n, vec in EXPLODE.items():
                ob = OBJ[n]
                if e > 0 and ob.parent is not None:
                    rel = ob.parent.matrix_world.to_3x3().inverted() @ (bw @ Vector(vec))
                    ob.location = base_loc[n] + rel * e
                else:
                    ob.location = base_loc[n]
                rec.rec(ob, "location", ob.location, f)

            # ---------------- record joints ----------------
            rec.rec(root, "location", root.location, f)
            rec.rec(root, "rotation_euler", root.rotation_euler, f)
            rec.rec(body, "location", body.location, f)
            rec.rec(body, "rotation_euler", body.rotation_euler, f)
            for leg in M.LEGS:
                for key in ("abd", "hip", "knee"):
                    rec.rec(rig[key][leg], "rotation_euler", rig[key][leg].rotation_euler, f)
            for key in ("turret", "shoulder", "elbow", "wpitch", "wroll"):
                rec.rec(rig[key], "rotation_euler", rig[key].rotation_euler, f)
            for jf in rig["fingers"]:
                rec.rec(jf, "location", jf.location, f)
            for n in ("Lidar_Rotor", "Cooling_Fan_Rotor", "Gear_Drive", "Gear_Idler", "Gear_Output"):
                rec.rec(OBJ[n], "rotation_euler", OBJ[n].rotation_euler, f)
            rec.rec(power, "scale", power.scale, f)
    return rec, knee_d, time.time() - t0


