def build_stage():
    sc = bpy.context.scene
    floor_mat = bpy.data.materials.new("Stage_Floor")
    floor_mat.use_nodes = True
    nt = floor_mat.node_tree
    bsdf = nt.nodes["Principled BSDF"]
    bsdf.inputs["Roughness"].default_value = 0.55
    tex = nt.nodes.new("ShaderNodeTexChecker")
    tex.inputs["Scale"].default_value = 24.0
    tex.inputs["Color1"].default_value = (0.022, 0.024, 0.028, 1)
    tex.inputs["Color2"].default_value = (0.016, 0.017, 0.02, 1)
    nt.links.new(tex.outputs["Color"], bsdf.inputs["Base Color"])
    me = bpy.data.meshes.new("Stage_Floor")
    bm = bmesh.new()
    # cyclorama: flat floor that curves up into a back wall
    W, D, R, H = 14.0, 7.0, 2.5, 6.0
    prof = [(-D, 0.0)]
    for i in range(1, 13):
        a = (i / 12) * math.pi / 2
        prof.append((D - R + R * math.sin(a), R - R * math.cos(a)))
    prof.append((D, H))
    rows = []
    for x in (-W / 2, W / 2):
        rows.append([bm.verts.new((y, -x, z)) for y, z in prof])
    for i in range(len(prof) - 1):
        bm.faces.new((rows[0][i], rows[0][i + 1], rows[1][i + 1], rows[1][i]))
    bm.to_mesh(me)
    bm.free()
    for p in me.polygons:
        p.use_smooth = True
    me.materials.append(floor_mat)
    floor = bpy.data.objects.new("Stage_Cyclorama", me)
    floor.rotation_euler = (0, 0, math.pi * 0.75)
    STAGE_COLL.objects.link(floor)

    def area(name, loc, rot, energy, size, color=(1, 1, 1)):
        ld = bpy.data.lights.new(name, "AREA")
        ld.energy, ld.size, ld.color = energy, size, color
        ob = bpy.data.objects.new(name, ld)
        ob.location, ob.rotation_euler = loc, rot
        STAGE_COLL.objects.link(ob)
        return ob
    area("Key_Light", (2.2, -2.4, 3.2), (math.radians(48), 0, math.radians(42)), 700, 2.5, (1.0, 0.96, 0.9))
    area("Rim_Light", (-2.6, 2.0, 2.4), (math.radians(-55), 0, math.radians(220)), 900, 1.5, (0.65, 0.82, 1.0))
    area("Fill_Light", (-1.5, -3.0, 1.2), (math.radians(75), 0, math.radians(-25)), 260, 3.0)
    area("Front_Fill", (3.2, 0.6, 1.4), (math.radians(70), 0, math.radians(100)), 220, 2.0, (1.0, 0.92, 0.85))
    world = bpy.data.worlds.get("World") or bpy.data.worlds.new("World")
    sc.world = world
    world.use_nodes = True
    bg = world.node_tree.nodes.get("Background")
    bg.inputs["Color"].default_value = (0.03, 0.034, 0.045, 1)
    bg.inputs["Strength"].default_value = 1.0

    # ---- cameras -----------------------------------------------------------
    target = empty("Cam_Target", OBJ["Body"], (0.05, 0, -0.08), 0.1, "SPHERE", coll=STAGE_COLL)

    knee_t = empty("Cam_Target_Knee", OBJ["Body"], (0.30, -0.24, -0.33), 0.05, "SPHERE", coll=STAGE_COLL)

    def cam(name, loc, lens=40, parent=None, track=True, tgt=None):
        cd = bpy.data.cameras.new(name)
        cd.lens = lens
        cd.dof.use_dof = True
        cd.dof.focus_object = tgt or target
        cd.dof.aperture_fstop = 5.6
        ob = bpy.data.objects.new(name, cd)
        ob.location = loc
        ob.parent = parent
        STAGE_COLL.objects.link(ob)
        if track:
            c = ob.constraints.new("TRACK_TO")
            c.target = tgt or target
            c.track_axis, c.up_axis = "TRACK_NEGATIVE_Z", "UP_Y"
        return ob

    rootp = OBJ["ARGO_Q4"]
    cams = {
        "Cam_Hero": cam("Cam_Hero", (2.1, -1.75, 1.05), 45, rootp),
        "Cam_Hero_Left": cam("Cam_Hero_Left", (1.6, 2.1, 1.15), 45, rootp),
        "Cam_Side": cam("Cam_Side", (0.1, -2.9, 0.62), 50, rootp),
        "Cam_Top": cam("Cam_Top", (0.6, -0.4, 3.2), 62, rootp),
        "Cam_Head": cam("Cam_Head", (1.35, -0.5, 0.8), 70, rootp),
        "Cam_Knee": cam("Cam_Knee", (1.15, -1.35, 0.32), 55, rootp, tgt=knee_t),
        "Cam_Wide": cam("Cam_Wide", (3.3, -2.8, 1.75), 38, rootp),
    }
    orbit = empty("Cam_Orbit_Rig", rootp, (0, 0, 0), 0.2, "CIRCLE", coll=STAGE_COLL)
    cams["Cam_Orbit"] = cam("Cam_Orbit", (2.5, 0, 1.15), 42, orbit)
    tl = M.timeline()
    end = tl[-1]["end"]
    orbit.rotation_euler = (0, 0, 0)
    orbit.keyframe_insert("rotation_euler", index=2, frame=1)
    orbit.rotation_euler = (0, 0, TAU * 3)
    orbit.keyframe_insert("rotation_euler", index=2, frame=end)
    shots = {"power_on": "Cam_Head", "startup": "Cam_Hero", "idle": "Cam_Orbit", "joint_demo": "Cam_Hero_Left",
             "walk": "Cam_Side", "arm": "Cam_Hero", "interact": "Cam_Hero_Left", "full": "Cam_Orbit",
             "shutdown": "Cam_Hero", "exploded": "Cam_Orbit"}
    sc.timeline_markers.clear()
    for c in tl:
        mk = sc.timeline_markers.new(c["label"], frame=c["start"])
        mk.camera = cams[shots[c["id"]]]
    sc.camera = cams["Cam_Hero"]
    return cams


def setup_render(res=(1920, 1080)):
    sc = bpy.context.scene
    for eng in ("BLENDER_EEVEE_NEXT", "BLENDER_EEVEE"):
        try:
            sc.render.engine = eng
            break
        except TypeError:
            continue
    sc.render.resolution_x, sc.render.resolution_y = res
    sc.render.resolution_percentage = 100
    ee = sc.eevee
    for attr, val in (("taa_render_samples", 64), ("use_gtao", True), ("use_bloom", True),
                      ("use_raytracing", True), ("use_shadows", True)):
        if hasattr(ee, attr):
            try:
                setattr(ee, attr, val)
            except Exception:
                pass
    try:
        sc.view_settings.view_transform = "AgX"
        sc.view_settings.look = "AgX - Medium High Contrast"
    except Exception:
        pass


