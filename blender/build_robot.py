def drive_emission(power_obj):
    """Emission strength of glowing materials follows the Power_Level empty."""
    for name, base in (("Glow_Cyan", 6.0), ("Glow_Amber", 4.0)):
        b = MAT[name].node_tree.nodes.get("Principled BSDF")
        fc = b.inputs["Emission Strength"].driver_add("default_value")
        d = fc.driver
        d.type = "SCRIPTED"
        v = d.variables.new()
        v.name = "p"
        v.type = "TRANSFORMS"
        v.targets[0].id = power_obj
        v.targets[0].transform_type = "SCALE_X"
        v.targets[0].transform_space = "LOCAL_SPACE"
        d.expression = f"p*{base}"


